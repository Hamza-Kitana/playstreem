export const RIDDLE_COUNTS = [10, 20, 50, 100] as const;
export const RIDDLE_ROUND = 10;

export function shuffleRiddles(list: Riddle[]): Riddle[] {
  const arr = [...list];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j]!, arr[i]!];
  }
  return arr;
}

export function pickRiddleRound(bank = RIDDLE_BANK, count = RIDDLE_ROUND) {
  return shuffleRiddles(bank).slice(0, Math.min(count, bank.length));
}

export function riddleMatches(guess: string, riddle: Riddle, normalize: (s: string) => string) {
  const g = normalize(guess);
  if (!g) return false;
  const keys = [riddle.answer, ...riddle.aliases].map((x) => normalize(x)).filter(Boolean);
  return keys.some((key) => {
    if (g === key) return true;
    if (key.length >= 4 && (g.includes(key) || (g.length >= 4 && key.includes(g)))) return true;
    return false;
  });
}
